"""Change 80 XP evidence: before/after tables from the farming measurements and exact XP arithmetic.

  python docs/Change_80_Evidence/xp_tables.py <xp_before.csv> <xp_after.csv> > docs/Change_80_Evidence/xp_tables.md

Measured (CSV, tests/change_80_xp_audit.tscn on HEAD 80c0bf4 and on Change 80): kills, XP and deaths of a
5-minute Focus farm of one standard spot (3 enemies, real respawns) per build and type, seeds 1-3.
Computed (exact, from the catalog rules): XP per level ceil(12 x L^1.35) and the levels one boss kill gives.
"""
import csv, math, sys
from collections import defaultdict

BEFORE = {'unit-horned-hood': 77, 'unit-orange-screen-helmet': 101, 'unit-television-head': 137, 'unit-top-hat': 180,
          'unit-bunny-ears': 358, 'unit-cat-ears': 600, 'unit-elf-ears': 1005, 'unit-flower-crown': 2821, 'unit-green-cap': 3978,
          'unit-pink-cap': 5612, 'unit-pink-flower-hood': 7916, 'unit-plain': 11166, 'unit-sprout': 15750,
          'boss-black-cat': 3020, 'boss-grim-reaper': 3580, 'boss-bee': 20000, 'boss-orange-tabby-cat': 23750,
          'boss-red-panda': 879610, 'boss-sunflower': 1044700, 'boss-green-alien': 4912510}
AFTER = dict(BEFORE, **{'unit-bunny-ears': 500, 'unit-cat-ears': 650, 'unit-elf-ears': 850, 'unit-flower-crown': 1050,
                        'unit-green-cap': 1250, 'unit-pink-cap': 1500, 'unit-pink-flower-hood': 1800, 'unit-plain': 2150,
                        'unit-sprout': 2550, 'boss-red-panda': 30000, 'boss-sunflower': 35000, 'boss-green-alien': 45000})


def req(level):
    return math.ceil(12 * level ** 1.35)


def levels_from(level, xp):
    gained = 0
    while xp >= req(level):
        xp -= req(level); level += 1; gained += 1
    return gained


def load(path):
    rows = defaultdict(list)
    for r in csv.DictReader(open(path, encoding='utf-8')):
        if r['result'] != 'farm':
            continue
        rows[(r['build'], int(r['level']), r['target'])].append(r)
    return rows


def name(t):
    return t.replace('unit-', '').replace('boss-', '').replace('-', ' ').title()


def main():
    before, after = load(sys.argv[1]), load(sys.argv[2])
    print('# Change 80 XP tables (generated by xp_tables.py)\n')
    print('## Base XP per kill\n\n| Type | Before | After | Change |\n|---|---:|---:|---:|')
    for t in AFTER:
        if BEFORE[t] != AFTER[t] or t.startswith('boss-bee') or t.startswith('boss-orange'):
            print('| %s | %s | %s | %+.0f%% |' % (name(t), f'{BEFORE[t]:,}', f'{AFTER[t]:,}', (AFTER[t] / BEFORE[t] - 1) * 100))
    print('\n## Measured farming (5 min Focus farm, standard spot of 3, seeds 1-3; means)\n')
    print('XP/min and time to the next level are at the build\'s starting level; "levels in 5 min" is what the run actually gained.\n')
    print('| Build | Lv | Type | Kills/min | Deaths | XP/level | XP/min before | XP/min after | Min/level before | Min/level after | Levels in 5 min before | after |')
    print('|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
    for key in after:
        b_rows, a_rows = before.get(key, []), after[key]
        build, level, target = key
        mean = lambda rows, f: sum(float(r[f]) for r in rows) / max(1, len(rows))
        km_a = mean(a_rows, 'kills') / mean(a_rows, 'minutes')
        xm_a = mean(a_rows, 'xp') / mean(a_rows, 'minutes')
        xm_b = mean(b_rows, 'xp') / mean(b_rows, 'minutes') if b_rows else float('nan')
        # XP/min at the starting level: kills/min x base XP (no XP upgrades or cards in these builds).
        km_b = mean(b_rows, 'kills') / mean(b_rows, 'minutes') if b_rows else float('nan')
        xb0, xa0 = km_b * BEFORE[target], km_a * AFTER[target]
        lv_b = levels_from(level, mean(b_rows, 'xp')) if b_rows else 0
        lv_a = levels_from(level, mean(a_rows, 'xp'))
        mpl = lambda x: req(level) / x if x > 0 else float('inf')
        print('| %s | %d | %s | %.1f | %.1f | %s | %s | %s | %.2f | %.2f | %d | %d |' % (
            build, level, name(target), km_a, mean(a_rows, 'deaths'), f'{req(level):,}', f'{xb0:,.0f}', f'{xa0:,.0f}',
            mpl(xb0), mpl(xa0), lv_b, lv_a))
    print('\n## One boss kill (exact; base XP, no multipliers)\n')
    print('| Boss | Level | XP/level | Levels before | Levels after |\n|---|---:|---:|---:|---:|')
    for t, lv in [('boss-black-cat', 135), ('boss-grim-reaper', 135), ('boss-bee', 150), ('boss-orange-tabby-cat', 150), ('boss-bee', 190),
                  ('boss-red-panda', 165), ('boss-red-panda', 192), ('boss-sunflower', 165), ('boss-sunflower', 192),
                  ('boss-green-alien', 165), ('boss-green-alien', 192), ('boss-green-alien', 235)]:
        print('| %s | %d | %s | %d | %d |' % (name(t), lv, f'{req(lv):,}', levels_from(lv, BEFORE[t]), levels_from(lv, AFTER[t])))
    print('\n## XP per level (unchanged formula ceil(12 x L^1.35))\n')
    print('| Level | ' + ' | '.join(str(l) for l in [63, 100, 137, 150, 165, 190, 192, 235]) + ' |')
    print('|---|' + '---:|' * 8)
    print('| XP | ' + ' | '.join(f'{req(l):,}' for l in [63, 100, 137, 150, 165, 190, 192, 235]) + ' |')


if __name__ == '__main__':
    main()
